/// Fallback that guarantees MaterialLocalizations is ALWAYS available.
///
/// Samsung devices may resolve a locale carrying a countryCode that
/// GlobalMaterialLocalizations.delegate does not natively support (e.g.
/// r_BJ, n_XA, or any of the ~60 extra languages in the picker).
/// When that happens the framework skips loading MaterialLocalizations, so
/// MaterialLocalizations.of(context) returns null which crashes BackButton,
/// BottomNavigationBar, etc. (Null check operator used on a null value).
/// This delegate supports every locale and falls back to English when the
/// framework delegate cannot load one.
class _FallbackMaterialLocalizationsDelegate
    extends LocalizationsDelegate<MaterialLocalizations> {
  const _FallbackMaterialLocalizationsDelegate();

  @override
  bool isSupported(Locale locale) => true;

  @override
  Future<MaterialLocalizations> load(Locale locale) async {
    try {
      return await GlobalMaterialLocalizations.delegate.load(
        Locale(locale.languageCode, locale.countryCode),
      );
    } catch (_) {
      return await GlobalMaterialLocalizations.delegate.load(const Locale('en'));
    }
  }

  @override
  bool shouldReload(_FallbackMaterialLocalizationsDelegate old) => false;
}

